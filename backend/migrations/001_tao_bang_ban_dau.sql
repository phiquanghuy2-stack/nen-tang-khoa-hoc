CREATE TABLE IF NOT EXISTS nguoidung (
  id INT AUTO_INCREMENT PRIMARY KEY,
  tenDangNhap VARCHAR(50) NOT NULL UNIQUE,
  email VARCHAR(100) NOT NULL UNIQUE,
  matKhau VARCHAR(255) NOT NULL,
  vaiTro VARCHAR(20) NOT NULL DEFAULT 'user',
  ngayTao TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS khoahoc (
  id INT AUTO_INCREMENT PRIMARY KEY,
  tieuDe VARCHAR(200) NOT NULL,
  moTa TEXT,
  gia INT NOT NULL DEFAULT 0,
  anhBia VARCHAR(500),
  capDo VARCHAR(30) NOT NULL,
  trangThai VARCHAR(20) NOT NULL DEFAULT 'nhap',
  ngayTao TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS baihoc (
  id INT AUTO_INCREMENT PRIMARY KEY,
  khoaHocId INT NOT NULL,
  tieuDe VARCHAR(200) NOT NULL,
  noiDung TEXT,
  videoUrl VARCHAR(500),
  thuTu INT NOT NULL DEFAULT 0,
  thoiLuong INT NOT NULL DEFAULT 0,
  xemThu BOOLEAN NOT NULL DEFAULT FALSE,
  FOREIGN KEY (khoaHocId) REFERENCES khoahoc(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS ghidanh (
  id INT AUTO_INCREMENT PRIMARY KEY,
  nguoiDungId INT NOT NULL,
  khoaHocId INT NOT NULL,
  trangThaiThanhToan VARCHAR(20) NOT NULL DEFAULT 'cho',
  ngayDangKy TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY mot_nguoi_mot_khoa (nguoiDungId, khoaHocId),
  FOREIGN KEY (nguoiDungId) REFERENCES nguoidung(id) ON DELETE CASCADE,
  FOREIGN KEY (khoaHocId) REFERENCES khoahoc(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS tiendo (
  id INT AUTO_INCREMENT PRIMARY KEY,
  nguoiDungId INT NOT NULL,
  baiHocId INT NOT NULL,
  daHoanThanh BOOLEAN NOT NULL DEFAULT FALSE,
  UNIQUE KEY mot_nguoi_mot_bai (nguoiDungId, baiHocId),
  FOREIGN KEY (nguoiDungId) REFERENCES nguoidung(id) ON DELETE CASCADE,
  FOREIGN KEY (baiHocId) REFERENCES baihoc(id) ON DELETE CASCADE
);